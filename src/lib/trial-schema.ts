import { z } from "zod";
import { digitsOnly, CALL_TIMES, REFERRERS } from "./contact-schema";

/**
 * 무료체험 신청 스키마 — 성함 · 연락처 · 연락 가능 시간대 · 이메일 · 회사명(매장명).
 *
 * ── 왜 이만큼인가 ──
 * 체험 계정을 열어드리고 사용 방법을 안내하는 데 필요한 최소값이다. 상담
 * 신청서와 같은 항목(업종·매장 수·지역)을 여기서 또 받으면 "일단 써보려던
 * 사람"이 상담 폼을 다시 만난 셈이 되어 이탈한다. CLAUDE.md §1.2 도 개인정보
 * 최소 수집을 요구한다 — 목적에 필요하지 않은 항목은 받지 않는다.
 *
 * ⚠️⚠️ **개인정보처리방침 제2조 개정 전에는 접수를 열지 않는다.**
 * 이름·연락처는 방침에 있는 항목이지만 **수집 목적("무료체험 신청 접수")이
 * 없다.** 목적 외 수집도 위반이므로 `trial/actions.ts` 의
 * `TRIAL_SINK_CONFIGURED` 는 false 이고, 운영 환경에서는 접수가 성사되지 않는다
 * (X-17). 방침 개정(X-02)과 저장소 연결(X-08)을 **같이** 하기 전에는 올리지 않는다.
 *
 * ── 상담 리드·소개서 요청과 섞지 않는다 ──
 * 세 데이터는 목적과 보유기간이 다르다(§1.2). 스키마를 따로 두어 나중에 한쪽만
 * 고치는 사고를 막는다.
 *
 * ── 체험 기간은 14일로 확정됐다 (2026-09-04) ──
 * 기획 문서마다 14일과 7일이 갈려 그동안 숫자를 쓰지 않았다(현황판 X-15). 안내는
 * `/trial` 페이지 한 곳에서 하고, 요금 카드 버튼 라벨에는 넣지 않는다.
 */

/*
  ── 2026-09-04 소개서 폼과 양식을 통일했다 (노션 「반오토 폼양식 수정」) ──
  그때는 성함 › 연락처 › 이메일 › 회사명 또는 매장명 › 어떻게 알고 오셨나요 순서로
  두 폼이 같은 모양이었다.

  ── 2026-09-08 두 폼이 갈라졌다 (사용자 확정) ──
  `연락 가능 시간대` 를 **무료체험에만** 넣었다. 소개서에는 넣지 않는다 — 사용자가
  "소개서에는 연락 가능 시간대 추가 안 해도 된다, 무료체험에만 넣자" 로 정정했다.
  그래서 지금 순서는 성함 › 연락처 › **연락 가능 시간대** › 이메일 › 회사명 또는
  매장명 › 어떻게 알고 오셨나요 다.

  ⚠️ **"두 폼을 항상 같게 유지" 는 더 이상 규칙이 아니다.** 함께 맞추는 범위는 나머지
     다섯 칸(성함 · 연락처 · 이메일 · 회사명 또는 매장명 · 유입 경로)의 **순서와
     라벨**뿐이다. 그 다섯 개를 고칠 때만 `lib/brochure-schema.ts` 와
     `brochure/BrochureForm.tsx` 를 함께 본다. 무료체험에만 있는 칸을 소개서로 옮기지
     않는다.

  ⚠️⚠️ 개인정보처리방침 제2조(수집 항목)에 **없는 항목이 이 폼에 두 개** 있다 —
     **이메일**(2026-09-04 추가) · **연락 가능 시간대**(2026-09-08 추가). 방침은
     "이름, 연락처" 만 허용한다(현황판 X-02). 사용자가 두 번 모두 **방침을 노션에서
     갱신하는 것으로 정리**하고 진행을 확정했다. 방침 개정 때 이 두 항목을 함께 넣어야
     한다 — 개정 전까지는 받는 항목과 고지가 어긋난 상태다.
*/
export const trialSchema = z
  .object({
    name: z.string().trim().min(2, "성함을 2자 이상 입력해 주세요").max(30, "성함이 너무 깁니다"),

    // 저장·검증은 숫자만으로 한다. 화면 표시만 하이픈을 넣는다(상담 폼과 동일).
    phone: z
      .string()
      .transform(digitsOnly)
      .refine((v) => /^01[016789]\d{7,8}$/.test(v), "휴대폰 번호를 정확히 입력해 주세요"),

    /*
      연락 가능 시간대 — 연락처 **바로 밑**에 둔다(사용자 지시 2026-09-08). 번호를 적은
      직후에 "언제 받으실 수 있나요" 를 묻는 것이 자연스럽다. 선택지는 상담·지원 폼과
      **같은 목록**(`CALL_TIMES`)을 쓴다 — 네 폼이 같은 목록을 봐야 시간대별 집계를 한
      기준으로 볼 수 있다. 필수다(상담·지원과 동일) — 언제 걸어야 받는지 모르면
      담당자가 헛걸음한다.

      ⚠️ 접수 API 는 **아직 이 필드를 받지 않는다.** 문서에 "정의에 없는 키는 저장하지
         않습니다" 라고 명시돼 있어 지금 보내면 조용히 버려진다(이슈 #36). 상담·지원
         폼도 같은 사정이다 — API 에 `callTime` 이 생기면 그때부터 저장된다. 화면·검증은
         지금부터 정상 동작한다.
    */
    callTime: z.enum(CALL_TIMES, { message: "연락 가능한 시간대를 선택해 주세요" }),

    // 체험 계정 안내를 보낼 곳. 형식만 본다 — 존재 여부는 발송 시점에 드러난다.
    email: z
      .string()
      .trim()
      .max(120, "이메일 주소가 너무 깁니다")
      .refine((v) => /^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(v), "이메일 주소를 정확히 입력해 주세요"),

    company: z
      .string()
      .trim()
      .min(2, "회사명 또는 매장명을 2자 이상 입력해 주세요")
      .max(60, "회사명이 너무 깁니다"),

    // 선택 항목. 선택지는 상담·소개서 폼과 **같은 목록**(`REFERRERS`)을 쓴다
    referrer: z.union([z.enum(REFERRERS), z.literal("")]).optional(),
    referrerDetail: z.string().trim().max(50, "50자 이내로 입력해 주세요").optional(),

    agreePrivacy: z.literal(true, { message: "개인정보 수집·이용에 동의해 주세요" }),
  })
  // `기타` 가 아니면 직접 입력값을 버린다(상담·소개서 폼과 같은 처리)
  .transform((v) => (v.referrer === "기타" ? v : { ...v, referrerDetail: undefined }));

export type TrialInput = z.input<typeof trialSchema>;
export type TrialData = z.output<typeof trialSchema>;
