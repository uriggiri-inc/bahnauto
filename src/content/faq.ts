/** 발췌 문항을 정본에서 찾아 순서대로 돌려준다 */
export function pricingFaqItems(): readonly FaqItem[] {
  const all = FAQ_GROUPS.flatMap((g) => g.items);
  return PRICING_FAQ_PICK.map((q) => all.find((i) => i.q === q)).filter(
    (i): i is FaqItem => i !== undefined,
  );
}
