/**
 * 요금 구성 — **기본료 하나 + 옵션 여섯**.
 *
 * ── 2026-08-27 전면 개편 ──
 * 이전에는 베이직·스탠다드·프리미엄 3플랜이었다. 담당자 수정안이 구조 자체를
 * 바꿨다: **운영 대시보드를 기본으로 깔고, 나머지 여섯 기능을 옵션으로 더한다.**
 * 사라진 것과 그 이유:
 *
 * | 사라진 것 | 이유 |
 * |---|---|
 * | 플랜 3종 · 추천 배지 | 묶음이 없어졌다. 고를 것은 "어느 플랜" 이 아니라 "어느 옵션" 이다 |
 * | 월간 / 연간 토글 | 수정안에 연간 결제가 없다. 값도 함께 지웠다(`dummy.ts`) |
 * | 옵션 단가 표 | 옵션 금액을 **전부 비공개**로 확정 — "옵션 별 금액이 상이합니다" |
 * | 요금 계산기 | 폐기하고 "도입 상담에서 안내"로 대체(사용자 확정 2026-08-27) |
 *
 * ── 금액은 하나뿐이다 ──
 * 화면에 뜨는 공개 금액은 기본료 **24,900원/월** 하나다. 근거가 아직 없어
 * `dummy.ts` 의 `DUMMY_BASE_PRICE` 를 거친다 — `DUMMY_CONTENT` 가 true 인 동안
 * "샘플 데이터" 배너가 함께 뜬다.
 *
 * ⚠️ **옵션 금액을 이 파일에 적지 않는다.** 비공개가 기획 확정 사항이므로 값 자체를
 *    두지 않아야 새어 나갈 경로가 없다. 조합 요금은 상담에서 안내한다.
 *
 * ── CTA 문구에 무료체험 "기간"을 넣지 않는다 ──
 * 기획 문서마다 14일과 7일이 갈린다. 확정 전까지 숫자를 카피에 박으면 나중에
 * 여러 화면을 뒤져야 한다. 기간이 확정되면 그때 한 곳에 상수로 둔다.
 */

import { DUMMY_BASE_PRICE } from "./dummy";
import { FEATURES, FEATURE_BY_KEY, type Feature } from "./features";

/**
 * 기본으로 제공되는 기능의 키. 이 하나만 기본이고 나머지는 전부 옵션이다.
 *
 * 문자열을 두 번 적지 않으려고 상수로 뺐다 — 아래 `PLAN_BASE` 와 `planOptions()`
 * 가 같은 값을 봐야 "기본에 든 것이 옵션 목록에도 있다" 같은 사고가 나지 않는다.
 */
export const BASE_FEATURE_KEY = "dashboard";

export type PlanBase = {
  /** 카드 제목 — `features.ts` 의 이름을 그대로 쓴다 */
  name: string;
  /** 월 요금(원, VAT 별도) */
  monthly: number;
  /** 카드 CTA */
  cta: { label: string; href: string };
};

/**
 * 기본료 카드 (수정안 목업의 왼쪽 브랜드 컬러 카드).
 *
 * CTA 는 **무료체험**이다. 한동안 상담(`/contact`)으로 보냈다 — 체험할 실체가
 * 없는데 "무료체험" 이라고 적으면 표시광고법 문제이고, 눌러서 상담 폼이 나오면
 * 속았다고 느끼기 때문이다. 체험용 웹 대시보드 주소가 확보되면서(2026-08-14 확정)
 * 도착지가 생겼고, 신청 화면 `/trial` 을 거쳐 그쪽으로 넘긴다.
 *
 * ⚠️ 라벨에 기간(14일·7일)을 넣지 않는다 — 기획 문서마다 값이 갈린다(파일 머리 주석).
 */
export const PLAN_BASE: PlanBase = {
  name: FEATURE_BY_KEY[BASE_FEATURE_KEY].title,
  monthly: DUMMY_BASE_PRICE,
  cta: { label: "무료체험하기", href: "/trial" },
};

/** 옵션 카드 CTA — 금액이 비공개라 도착지는 상담 하나뿐이다 */
export const PLAN_OPTION_CTA = { label: "서비스 문의", href: "/contact" } as const;

/**
 * 옵션으로 붙는 기능들 — **기본 기능을 뺀 나머지 전부**, `features.ts` 순서 그대로.
 *
 * 목록을 손으로 다시 적지 않는 이유: 기능이 추가·삭제될 때 한쪽만 고쳐지면
 * 요금 화면과 주요기능 화면이 갈라진다. 순서도 `features.ts` 가 정본이다
 * (수정안 목업의 옵션 나열 순서와 같다).
 */
export function planOptions(): readonly Feature[] {
  return FEATURES.filter((f) => f.key !== BASE_FEATURE_KEY);
}

/**
 * 카드 아래 각주 — 담당자 수정안 문구 그대로다.
 *
 * "표시 금액은 VAT 별도" 와 "옵션 조합 요금은 상담에서" 를 **한 문장에** 둔다.
 * 두 줄로 나누면 아래쪽이 각주의 각주처럼 읽혀 놓친다.
 */
export const PRICING_FOOTNOTE =
  "표시 금액은 VAT 별도이며, 옵션 추가 및 조합 요금은 도입 상담에서 안내드립니다.";

/** 옵션 카드 안의 작은 안내 — 금액을 적지 않는 이유를 화면에서도 밝힌다 */
export const PLAN_OPTION_NOTE = "옵션 별 금액이 상이합니다";
