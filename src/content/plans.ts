/* ═══════════════════════════════════════════════════════════════
   옵션별 구성표 — 담당자 `반오토_요금제_항목별_구성표.docx` 정본
   (사용자 지시 2026-08-28)

   요금 카드 아래가 비어 보인다는 지적에 따라 홈 요금 섹션에 넣는 표다.
   **금액이 아니라 "무엇이 들어가고 어떻게 결제하는가" 를 말한다** — 옵션 금액은
   여전히 비공개이고, 이 표에도 금액은 없다.

   ── 항목 이름을 여기 적지 않는다 ──
   `key` 로 `features.ts` 를 가리킨다. 문서는 `방문관리서비스`(붙여쓰기)로 적었지만
   사이트 정본은 `방문관리 서비스`(띄어쓰기, `반오토 주요기능 수정.html` 기준)다.
   같은 화면 바로 위 "옵션 기능 목록" 과 표기가 갈라지면 다른 것으로 읽히므로
   **이름은 항상 `features.ts` 에서 가져온다.**

   ── 포함 내용을 배열로 끊은 기준 ──
   문서는 한 칸에 쉼표로 이어 적었다. 괄호 **밖의** 쉼표에서만 끊어 목록으로
   만들었다 — 괄호 안(`업무 체크리스트, 재고 관리, 출퇴근 관리`)은 상위 항목의
   세부라서 함께 묶여 있어야 뜻이 유지된다.

   ── 연간 결제는 **글자로만** 적는다 (사용자 확정 2026-08-28) ──
   2026-08-27 요금 개편에서 월간/연간 토글을 없앴는데(수정안에 연간 결제가 없었다)
   이 문서는 ⑥·⑦ 을 **연간 결제 전용**으로 적는다. 사이트에 연간 결제를 안내하는
   화면은 없다.

   그래도 **표에 적힌 그대로 표시만 한다.** 확인 결과 사용자 확정 사항이다 —
   "표시 그대로 작성만 해주면 되고 따로 링크하거나 토글 만들 필요가 없어".

   ⚠️ 그래서 `결제방식` 은 **링크가 아니고 토글도 아니다.** 누르는 것이 없는
      글자 배지다(`PlanCompositionTable` 의 `BillingBadge`). 다음에 이 값을 보고
      "연간 결제 화면이 빠졌다" 고 판단해 토글이나 연간 요금 페이지를 만들지
      말 것 — 없는 것이 의도다. 연간 금액을 실제로 안내하게 되면 그때
      기획을 다시 받는다.

   ⚠️ ④ 고객센터의 `24시간 챗봇 + 9 to 9 본사 고객센터` 는 그동안 갈렸던 표기를
      **해소한다.** 챗봇은 24시간, 본사 고객센터 연결은 9 to 9 로 둘 다 맞다
      (`feature-details.ts` 머리 주석의 경고 대상이었다).
   ═══════════════════════════════════════════════════════════════ */

