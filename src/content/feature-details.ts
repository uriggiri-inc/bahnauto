export type DetailCard = { title: string; body: string };

/**
 * 기능별 실제 화면 자리.
 *
 * ── 캡처가 없는 화면은 적지 않는다 (2026-08-25 사용자 확정) ──
 * 이전에는 자리를 미리 만들어 두고 자리표시자를 그렸다. 그런데 자리표시자가
 * 라이브에 남아 있으면 사이트가 미완성으로 보인다. 그래서 **캡처가 있는 화면만**
 * 적고, 화면이 0개인 기능은 "실제 화면" 섹션 자체가 렌더되지 않는다.
 *
 * 확보해야 할 화면 목록은 코드가 아니라 **별도 문서**로 관리한다 — 코드에 빈
 * 항목으로 남겨 두면 그게 곧 자리표시자가 된다.
 *
 * ⚠️ 캡처를 넣을 때 **실제 매장명·연락처·사람 이름을 마스킹**한다(CLAUDE.md §5).
 */
/**
 * 기능 상세의 "실제 화면" 한 장.
 *
 * `width`/`height` 는 **틀을 쓰지 않기 때문에** 필요하다(사용자 확정 2026-08-25).
 * 화면비를 강제하면 해상도가 다른 캡처가 잘리므로, 원본 크기로 비율을 잡는다.
 *
 * ⚠️ **지금은 일곱 기능 모두 `screens` 가 비어 있다.** 캡처가 있는 기능은 전부
 *    슬라이드(`app-screens.ts` 의 `FEATURE_CAROUSELS`)로 보여준다 — 한 기능에
 *    화면이 여러 장이면 한 줄에 늘어놓을 자리가 없기 때문이다. 이 필드를 남겨
 *    두는 이유는 **캡처가 한 장뿐인 기능**(② 기본서비스 · ④ 고객센터가 그렇게
 *    될 예정이다)이다. 한 장을 슬라이드로 감싸면 넘길 것도 없는 캐러셀이 된다.
 *
 * 가로(PC) 화면은 `2000×1093`, 세로(모바일)는 `756×1466` 이 실측값이다.
 */
export type FeatureScreen = {
  /** 어떤 화면인지. 캡처 확보 전에는 자리표시자에 이 문장이 그대로 보인다 */
  alt: string;
  /** 화면 아래 한 줄 — 기능마다 다른 이름을 쓴다 */
  caption: string;
  /** 마스킹 완료된 실제 캡처 경로. 확보되면 여기만 채운다 */
  src?: string;
  width: number;
  height: number;
};

export type DetailGroup = {
  /** 그룹 위 작은 라벨(한글). 없으면 제목만 나온다 */
  label?: string;
  /**
   * 시안의 **영문 눈썹**(`FOR MANAGER`). 있으면 눈썹 자리에 이것이 대문자로
   * 들어가고, 한글 `label` 은 제목 앞으로 옮겨 붙는다
   * (`매니저용 — 현장을 기록하는 4가지 기능`).
   *
   * 시안에서 확인된 그룹에만 채운다 — 영문 표기를 임의로 만들면 시안과
   * 갈라지고, 그러면 "똑같이"가 아니게 된다.
   */
  labelEn?: string;
  title: string;
  lead: string;
  cards: readonly DetailCard[];
};

export type FeatureDetail = {
  /** features.ts 의 key */
  key: string;
  /** 영문 eyebrow — 번호는 화면에서 붙인다 */
  eyebrow: string;
  /** 2줄 헤드라인. 둘째 줄이 브랜드 컬러로 강조된다 */
  headline: readonly [string, string];
  sub: string;
  /** 알약형 칩 2~3개 */
  chips: readonly string[];
  groups: readonly DetailGroup[];
  /** 실제 화면 자리. 캡처 미확보 상태에서도 자리는 그려진다 */
  screens: readonly FeatureScreen[];
  /**
   * 페이지 맨 위에 띠로 걸리는 알림. 아직 열지 않은 기능에 쓴다
   * (사용자 지시 2026-08-27).
   *
   * 내용을 지우지 않고 띠만 얹는 이유: 오픈 전에도 **무엇을 제공할지**는 보여줘야
   * 문의가 들어온다. 다만 지금 쓸 수 있다고 오해하면 안 되므로 맨 위에서 먼저
   * 알린다.
   */
  notice?: {
    /** 배지 문구 — 색이 아니라 글자로 상태를 말한다(이모지 금지) */
    badge: string;
    title: string;
    body: string;
  };
  /**
   * 도입 효과.
   *
   * ⚠️ **없어도 된다.** ⑦ A/S 바로출동서비스는 담당자 전달 문서에 "시설 고장 및
   *    긴급상황 출동 서비스 / 준비 중" 두 줄뿐이다. 효과를 채우려면 없는 내용을
   *    지어내야 하므로 아예 비운다(CLAUDE.md §5 — 검증되지 않은 내용 금지).
   *    범위가 확정되면 그때 채운다.
   */
  effect?: { title: string; items: readonly DetailCard[] };
};

